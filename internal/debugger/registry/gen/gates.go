const featuregatePkg = "go.opentelemetry.io/collector/featuregate"

type listed struct {
	ImportPath     string
	Dir            string
	GoFiles        []string
	IgnoredGoFiles []string
	Imports        []string
}

// writeGates finds where the worker registers its feature gates and writes
// gateowners.go: for each gate, whether the Collector's own packages link
// the registering package, and which component packages do. Components are
// the registry's componentTypes keys, read from components.go; the
// registry's other imports from outside this module (otelcol, the kinds'
// packages, the telemetry factory) are the Collector.
// It lists the worker's packages for linux, the runtimes' target, and also
// reads files excluded there, so a gate registered for another system is
// still found.
func writeGates(out, source string) error {
	// The main module of this directory: go generate runs in the registry
	// package, a build in its module's root, which has no Go files. Without
	// the workspace, go list -m names only that module.
	mod, err := goListEnv([]string{"GOWORK=off"}, "list", "-m", "-f", "{{.Path}}")
	if err != nil {
		return err
	}
	raw, err := goList("list", "-deps", "-json=ImportPath,Dir,GoFiles,IgnoredGoFiles,Imports",
		strings.TrimSpace(string(mod))+"/cmd/linea-worker")
	if err != nil {
		return err
	}
	pkgs := map[string]*listed{}
	for dec := json.NewDecoder(bytes.NewReader(raw)); ; {
		var p listed
		if err := dec.Decode(&p); err == io.EOF {
			break
		} else if err != nil {
			return fmt.Errorf("go list output: %w", err)
		}
		pkgs[p.ImportPath] = &p
	}
	registryPkg := strings.TrimSpace(string(mod)) + "/internal/debugger/registry"
	reg := pkgs[registryPkg]
	if reg == nil {
		return fmt.Errorf("the worker does not import %s", registryPkg)
	}
	components, err := componentPackages(filepath.Join(reg.Dir, "components.go"))
	if err != nil {
		return err
	}
	var roots []string
	for _, imp := range reg.Imports {
		if !slices.Contains(components, imp) && !strings.HasPrefix(imp, strings.TrimSpace(string(mod))+"/") {
			roots = append(roots, imp)
		}
	}
	collector := closure(pkgs, roots)
	byComponent := map[string]map[string]bool{}
	for _, c := range components {
		byComponent[c] = closure(pkgs, []string{c})
	}

	type owner struct {
		collector bool
		packages  []string
	}
	owners := map[string]*owner{}
	r := &resolver{pkgs: pkgs, files: map[string][]*ast.File{}}
	for path, p := range pkgs {
		if !slices.Contains(p.Imports, featuregatePkg) {
			continue
		}
		ids, err := r.registrations(path)
		if err != nil {
			return err
		}
		for _, id := range ids {
			o := owners[id]
			if o == nil {
				o = &owner{}
				owners[id] = o
			}
			o.collector = o.collector || collector[path]
			for _, c := range components {
				if byComponent[c][path] && !slices.Contains(o.packages, c) {
					o.packages = append(o.packages, c)
				}
			}
		}
	}

	ids := make([]string, 0, len(owners))
	for id := range owners {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/debugger/registry/gen from %s and the worker's source. DO NOT EDIT.\n\n", source)
	b.WriteString("package registry\n\n")
	b.WriteString("// gateOwners are the feature gates the worker's source registers, with\n")
	b.WriteString("// what links each registering package (gates.go).\n")
	b.WriteString("var gateOwners = map[string]gateOwner{\n")
	for _, id := range ids {
		o := owners[id]
		switch {
		case o.collector:
			fmt.Fprintf(&b, "\t%q: {collector: true},\n", id)
		case len(o.packages) == 0:
			fmt.Fprintf(&b, "\t%q: {},\n", id)
		default:
			slices.Sort(o.packages)
			fmt.Fprintf(&b, "\t%q: {packages: []string{", id)
			for i, p := range o.packages {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", p)
			}
			b.WriteString("}},\n")
		}
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("generated gate owners do not parse: %w", err)
	}
	return os.WriteFile(out, src, 0o644)
}

func goList(args ...string) ([]byte, error) {
	return goListEnv(nil, args...)
}

// goListEnv is goList with extra environment variables.
func goListEnv(env []string, args ...string) ([]byte, error) {
	cmd := exec.Command("go", args...)
	cmd.Env = append(append(os.Environ(), "GOOS=linux", "GOARCH=amd64"), env...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return out, nil
}

// componentPackages reads the packages componentTypes lists in a generated
// components.go: the first element of each {package, names} entry.
func componentPackages(file string) ([]string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Name.Name != "componentTypes" {
			continue
		}
		ast.Inspect(fn, func(n ast.Node) bool {
			if lit, ok := n.(*ast.CompositeLit); ok && len(lit.Elts) == 2 {
				if s, ok := lit.Elts[0].(*ast.BasicLit); ok && s.Kind == token.STRING {
					if p, err := strconv.Unquote(s.Value); err == nil && !slices.Contains(out, p) {
						out = append(out, p)
					}
				}
			}
			return true
		})
		return out, nil
	}
	return nil, fmt.Errorf("%s has no componentTypes: regenerate it", file)
}

// closure is every package reachable from roots, roots included.
func closure(pkgs map[string]*listed, roots []string) map[string]bool {
	seen := map[string]bool{}
	stack := slices.Clone(roots)
	for len(stack) > 0 {
		p := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		if seen[p] || pkgs[p] == nil {
			continue
		}
		seen[p] = true
		stack = append(stack, pkgs[p].Imports...)
	}
	return seen
}

// resolver reads the gate IDs a package registers: the first argument of
// each Register or MustRegister call in a file importing featuregate, a
// string literal or a string constant (of the package, or another listed
// package), concatenations included. IDs it cannot resolve are skipped.
type resolver struct {
	pkgs  map[string]*listed
	files map[string][]*ast.File
}

func (r *resolver) parse(path string) ([]*ast.File, error) {
	if f, ok := r.files[path]; ok {
		return f, nil
	}
	p := r.pkgs[path]
	var files []*ast.File
	if p != nil {
		fset := token.NewFileSet()
		for _, name := range append(slices.Clone(p.GoFiles), p.IgnoredGoFiles...) {
			if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
				continue
			}
			f, err := parser.ParseFile(fset, filepath.Join(p.Dir, name), nil, parser.SkipObjectResolution)
			if err != nil {
				continue // A file for another system may not parse with this Go; skip it.
			}
			files = append(files, f)
		}
	}
	r.files[path] = files
	return files, nil
}

func (r *resolver) registrations(path string) ([]string, error) {
	files, err := r.parse(path)
	if err != nil {
		return nil, err
	}
	var ids []string
	for _, f := range files {
		imports := fileImports(f)
		if !slices.Contains(mapValues(imports), featuregatePkg) {
			continue
		}
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) == 0 {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || (sel.Sel.Name != "MustRegister" && sel.Sel.Name != "Register") {
				return true
			}
			if id, ok := r.value(path, imports, call.Args[0], 0); ok && id != "" {
				ids = append(ids, id)
			}
			return true
		})
	}
	return ids, nil
}

func (r *resolver) value(path string, imports map[string]string, e ast.Expr, depth int) (string, bool) {
	if depth > 8 {
		return "", false
	}
	switch e := e.(type) {
	case *ast.BasicLit:
		if e.Kind != token.STRING {
			return "", false
		}
		s, err := strconv.Unquote(e.Value)
		return s, err == nil
	case *ast.ParenExpr:
		return r.value(path, imports, e.X, depth+1)
	case *ast.BinaryExpr:
		if e.Op != token.ADD {
			return "", false
		}
		x, ok := r.value(path, imports, e.X, depth+1)
		if !ok {
			return "", false
		}
		y, ok := r.value(path, imports, e.Y, depth+1)
		return x + y, ok
	case *ast.Ident:
		return r.constant(path, e.Name, depth+1)
	case *ast.SelectorExpr:
		if x, ok := e.X.(*ast.Ident); ok {
			if imp, ok := imports[x.Name]; ok {
				return r.constant(imp, e.Sel.Name, depth+1)
			}
		}
	}
	return "", false
}

// constant resolves a package-level string constant.
func (r *resolver) constant(path, name string, depth int) (string, bool) {
	files, _ := r.parse(path)
	for _, f := range files {
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.CONST {
				continue
			}
			for _, s := range g.Specs {
				v := s.(*ast.ValueSpec)
				for i, n := range v.Names {
					if n.Name == name && i < len(v.Values) {
						return r.value(path, fileImports(f), v.Values[i], depth)
					}
				}
			}
		}
	}
	return "", false
}

// fileImports maps a file's import names to their paths; an unnamed import
// is named by its last element, as most packages are.
func fileImports(f *ast.File) map[string]string {
	m := map[string]string{}
	for _, imp := range f.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			continue
		}
		name := filepath.Base(p)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		m[name] = p
	}
	return m
}

func mapValues(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for _, v := range m {
		out = append(out, v)
	}
	return out
}
