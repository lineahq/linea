// CLIRequest describes a build of the linea CLI with a manifest's
// components in process: the direct commands of the release CLI, on the
// manifest's Collector release and components instead of the built-in ones.
type CLIRequest struct {
	// Manifest is the OCB manifest.
	Manifest []byte
	// Source is the worker source (workersrc.Embedded or workersrc.Pack),
	// which holds the CLI's packages too.
	Source fs.FS
	// Set is the manifest release's dependency set; nil builds an
	// unverified CLI, resolving the release through the module source.
	Set *DependencySet
	// Sources are module sources supplied beside the manifest.
	Sources []ModuleSource
	// GOOS and GOARCH are the CLI's platform; empty means this host's.
	GOOS, GOARCH string
	// ModuleProxy and Offline are BuildRequest's.
	ModuleProxy string
	Offline     bool
	// GoImage, Memory and CPUs apply to Docker.BuildCLI only, as in
	// BuildRequest.
	GoImage string
	Memory  int64
	CPUs    float64
	// Log receives the build's output, line by line.
	Log func(line string)
}

// CLI is a built CLI binary.
type CLI struct {
	// Path is the binary, written where the build was asked to write it.
	Path string
	// Digest is "sha256:<hex>" of the binary and Size its length.
	Digest string
	Size   int64
	// CollectorVersion is the manifest's release; Verified is false for a
	// release outside the support table.
	CollectorVersion string
	Verified         bool
	// GOOS and GOARCH are the binary's platform.
	GOOS, GOARCH string
	// Checked is set when the build ran the binary's version command and
	// it announced the manifest's Collector and modules: only a build for
	// this host can run it.
	Checked bool
}

// cliStampFile is the generated file that tells a built CLI what it was
// built from; the release CLI has none (cmd/linea/version.go).
const cliStampFile = "cmd/linea/custom_build.go"

// cliStamp is the Go source of cliStampFile for a plan and its sources.
func cliStamp(p *buildPlan, sources []ModuleSource) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by linea build from the build's manifest. DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("func init() {\n")
	fmt.Fprintf(&b, "customBuild = &buildStamp{Verified: %t", p.verified)
	if len(sources) > 0 {
		b.WriteString(", Modules: []stampModule{\n")
		for _, s := range sources {
			fmt.Fprintf(&b, "{Module: %s, Source: %s, Commit: %s},\n", strconv.Quote(s.Module), strconv.Quote(stampOrigin(s.Origin)), strconv.Quote(s.Commit))
		}
		b.WriteString("}")
	}
	b.WriteString("}\n}\n")
	return format.Source([]byte(b.String()))
}

// stampOrigin is a source's origin without the credentials a git URL can
// carry, since the stamp ends up in the binary.
func stampOrigin(origin string) string {
	u, err := url.Parse(origin)
	if err != nil || u.User == nil {
		return origin
	}
	u.User = nil
	return u.String()
}

// cliLDFlags stamps the building debugger's version into a CLI and, for
// a release outside the support table, marks its Collector unverified, so
// its reports say so.
func cliLDFlags(verified bool) string {
	flags := "-ldflags=-s -w -X " + release.VersionVariable + "=" + release.ProductVersion
	if !verified {
		flags += " -X " + release.UnverifiedVariable + "=true"
	}
	return flags
}

// cliCompileArgs is the go build of the CLI into out.
func cliCompileArgs(out string, verified bool) []string {
	return buildArgs(cliLDFlags(verified), out, cliMain)
}

// cliPlan plans a CLI build: the runtime build's plan with the CLI's stamp.
func cliPlan(req CLIRequest) (*manifest.Manifest, *buildPlan, BuildRequest, error) {
	br := BuildRequest{
		Manifest: req.Manifest, Source: req.Source, Set: req.Set, Sources: req.Sources,
		GoImage: req.GoImage, ModuleProxy: req.ModuleProxy, Offline: req.Offline,
		Memory: req.Memory, CPUs: req.CPUs, Log: req.Log,
	}
	if br.Log == nil {
		br.Log = func(string) {}
	}
	if _, err := fs.Stat(req.Source, strings.TrimPrefix(cliMain, "./")+"/main.go"); err != nil {
		return nil, nil, br, errors.New("the worker source holds no CLI: rebuild this debugger after `go generate ./internal/debugger/workersrc`")
	}
	m, p, err := plan(br)
	if err != nil {
		return nil, nil, br, err
	}
	stamp, err := cliStamp(p, req.Sources)
	if err != nil {
		return nil, nil, br, err
	}
	p.extra = map[string][]byte{cliStampFile: stamp}
	// The CLI's own requirements are resolved with its packages.
	return m, p, br, nil
}

func cliTarget(req CLIRequest) (goos, goarch string) {
	goos, goarch = req.GOOS, req.GOARCH
	if goos == "" {
		goos = runtime.GOOS
	}
	if goarch == "" {
		goarch = runtime.GOARCH
	}
	return goos, goarch
}

// BuildCLI compiles the linea CLI with a manifest's components with the
// host's go command and writes it to out, replacing a file there only once
// the build succeeded. The gate generator runs for this host, the CLI
// compiles for the request's platform; a CLI for this host is started once
// to check that its version command names the manifest's Collector and
// modules. A failure after the steps started is a BuildError.
func (n *Native) BuildCLI(ctx context.Context, req CLIRequest, out string) (*CLI, error) {
	cli, err := n.buildCLI(ctx, req, out)
	return cli, cliError(err)
}

func (n *Native) buildCLI(ctx context.Context, req CLIRequest, out string) (*CLI, error) {
	m, p, br, err := cliPlan(req)
	if err != nil {
		return nil, err
	}
	d, err := n.dirs()
	if err != nil {
		return nil, err
	}
	goos, goarch := cliTarget(req)
	log := br.Log
	if !p.verified {
		log("Collector " + p.collectorVersion + " is not in this debugger's support table: building an unverified CLI")
	}
	buildDir, err := os.MkdirTemp(d.builds, "cli-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(buildDir)
	r := &nativeRun{n: n, d: d, req: br, log: log, dir: buildDir, main: cliMain, goos: goos, goarch: goarch}
	archive, goMod, _, err := p.buildModule(br, "", log, func(archive, goMod []byte) ([]byte, []byte, error) {
		return r.resolve(ctx, archive, goMod)
	})
	if err != nil {
		return nil, err
	}
	bin := filepath.Join(buildDir, "linea"+exeSuffix(goos))
	log("compiling the CLI for " + goos + "/" + goarch + " with " + GoVersion)
	dir, err := r.extract(archive)
	if err != nil {
		return nil, &BuildError{Stage: "compiling", Err: err}
	}
	if err := r.stepFor(ctx, "compiling", dir, goMod, false, runtime.GOOS, runtime.GOARCH, genArgs); err != nil {
		return nil, err
	}
	if err := r.step(ctx, "compiling", dir, goMod, false, cliCompileArgs(bin, p.verified)); err != nil {
		return nil, err
	}
	return finishCLI(ctx, m, p, goos, goarch, bin, out, log)
}

// BuildCLI compiles the linea CLI with a manifest's components in the Go
// image and writes it to out, as Native.BuildCLI does.
func (d *Docker) BuildCLI(ctx context.Context, req CLIRequest, out string) (*CLI, error) {
	cli, err := d.buildCLI(ctx, req, out)
	return cli, cliError(err)
}

func (d *Docker) buildCLI(ctx context.Context, req CLIRequest, out string) (*CLI, error) {
	m, p, br, err := cliPlan(req)
	if err != nil {
		return nil, err
	}
	if _, err := d.Version(ctx); err != nil {
		return nil, err
	}
	goImage := br.GoImage
	if goImage == "" {
		goImage = GoImage
	}
	goos, goarch := cliTarget(req)
	log := br.Log
	if !p.verified {
		log("Collector " + p.collectorVersion + " is not in this debugger's support table: building an unverified CLI")
	}
	target := "GOOS=" + goos + " GOARCH=" + goarch + " "
	missing := missingArgsFor(cliMain)
	archive, goMod, _, err := p.buildModule(br, " in "+goImage, log,
		func(archive, goMod []byte) ([]byte, []byte, error) {
			out, err := d.runGo(ctx, br, goImage, "resolving modules", archive, goMod, missing,
				target+"go "+shellJoin(resolveArgsFor(cliMain))+" >/dev/null", "tar -cf - go.mod go.sum", log)
			if err != nil {
				return nil, nil, err
			}
			goMod, goSum, err := untarModFiles(out)
			if err != nil {
				return nil, nil, &BuildError{Stage: "resolving modules", Err: err}
			}
			return goMod, goSum, nil
		})
	if err != nil {
		return nil, err
	}
	log("compiling the CLI for " + goos + "/" + goarch + " in " + goImage)
	raw, err := d.runGo(ctx, br, goImage, "compiling", archive, goMod, missing,
		"{ go "+shellJoin(genArgs)+" 1>&2 && "+target+"go "+shellJoin(cliCompileArgs("/tmp/linea", p.verified))+" 1>&2; }", "cat /tmp/linea", log)
	if err != nil {
		return nil, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(absOrSelf(out)), ".linea-build-*")
	if err != nil {
		return nil, err
	}
	bin := tmp.Name()
	defer os.Remove(bin)
	_, err = tmp.Write(raw)
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return nil, err
	}
	return finishCLI(ctx, m, p, goos, goarch, bin, out, log)
}

// cliError names a CLI build in its BuildError, which runtime builds share.
func cliError(err error) error {
	var be *BuildError
	if errors.As(err, &be) {
		be.What = "CLI"
	}
	return err
}

// finishCLI checks a compiled CLI, starting it when it is for this host,
// and moves it to out.
func finishCLI(ctx context.Context, m *manifest.Manifest, p *buildPlan, goos, goarch, bin, out string, log func(string)) (*CLI, error) {
	digest, size, err := hashFile(bin)
	if err != nil {
		return nil, &BuildError{Stage: "compiling", Err: err}
	}
	if size == 0 {
		return nil, &BuildError{Stage: "compiling", Err: errors.New("the build wrote no CLI")}
	}
	if err := os.Chmod(bin, 0o755); err != nil {
		return nil, err
	}
	c := &CLI{Digest: digest, Size: size, CollectorVersion: p.collectorVersion, Verified: p.verified, GOOS: goos, GOARCH: goarch}
	if goos == runtime.GOOS && goarch == runtime.GOARCH {
		log("starting the CLI's version command")
		if err := checkCLI(ctx, bin, p.collectorVersion, m.Modules()); err != nil {
			return nil, &BuildError{Stage: "starting the CLI", Err: err}
		}
		c.Checked = true
	} else {
		log("not started: the CLI is for " + goos + "/" + goarch + ", this host is " + runtime.GOOS + "/" + runtime.GOARCH)
	}
	if err := moveFile(bin, out); err != nil {
		return nil, err
	}
	if c.Path, err = filepath.Abs(out); err != nil {
		c.Path = out
	}
	log("built " + c.Path + " " + digest)
	return c, nil
}

// checkCLI runs a built CLI's version command and compares the Collector
// and modules it announces with the manifest's.
func checkCLI(ctx context.Context, bin, collector string, modules []string) error {
	ctx, cancel := context.WithTimeout(ctx, time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, bin, "version", "--format", "json")
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%w: %s", err, strings.TrimSpace(stderr.String()))
	}
	var v struct {
		Collector string   `json:"collector_version"`
		Modules   []string `json:"modules"`
	}
	if err := json.Unmarshal(stdout.Bytes(), &v); err != nil {
		return fmt.Errorf("the CLI's version output: %w", err)
	}
	if v.Collector != collector || !slices.Equal(v.Modules, modules) {
		return fmt.Errorf("the CLI announced Collector %s with %d modules, the manifest names %s with %d", v.Collector, len(v.Modules), collector, len(modules))
	}
	return nil
}

// moveFile renames src to dst, copying when they are on different volumes.
func moveFile(src, dst string) error {
	if err := os.Rename(src, dst); err == nil {
		return nil
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	tmp, err := os.CreateTemp(filepath.Dir(absOrSelf(dst)), ".linea-build-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	_, err = io.Copy(tmp, in)
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Chmod(tmp.Name(), 0o755)
	}
	if err == nil {
		err = os.Rename(tmp.Name(), dst)
	}
	return err
}

func absOrSelf(p string) string {
	if abs, err := filepath.Abs(p); err == nil {
		return abs
	}
	return p
}

func exeSuffix(goos string) string {
	if goos == "windows" {
		return ".exe"
	}
	return ""
}
