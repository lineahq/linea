// TestBuildPlanRefusesSourcesNeedingANewerRelease refuses, before
// resolution, a custom module requiring a Collector module above the
// verified release, naming the module and both versions.
func TestBuildPlanRefusesSourcesNeedingANewerRelease(t *testing.T) {
	p, err := planBuild(repoSource(t), parse(t, withStamp(t, "")), set162(t), []string{stampModule})
	if err != nil {
		t.Fatal(err)
	}
	goMod := func(component string) fstest.MapFS {
		return fstest.MapFS{"go.mod": {Data: []byte("module " + stampModule + "\n\ngo 1.25\n\nrequire (\n\tgo.opentelemetry.io/collector/component " + component + "\n\texample.com/other v0.9.0\n)\n")}}
	}
	if err := p.checkSources([]ModuleSource{{Module: stampModule, Files: goMod("v1.68.0")}, {Module: "example.com/later"}}); err != nil {
		t.Fatalf("a source on the release: %v", err)
	}
	err = p.checkSources([]ModuleSource{{Module: stampModule, Files: goMod("v1.69.0")}})
	var me *ModuleError
	if !errors.As(err, &me) || !strings.Contains(err.Error(), stampModule+" requires go.opentelemetry.io/collector/component v1.69.0; Collector 0.162.0 has v1.68.0") ||
		!strings.Contains(err.Error(), "build at the release its go.mod requires") {
		t.Fatalf("got %v", err)
	}
	unverified, err := planBuild(repoSource(t), parse(t, withStamp(t, "")), nil, []string{stampModule})
	if err != nil {
		t.Fatal(err)
	}
	if err := unverified.checkSources([]ModuleSource{{Module: stampModule, Files: goMod("v1.69.0")}}); err != nil {
		t.Fatalf("an unverified release: %v", err)
	}
}

// TestBuildsCompileTheSourcesProviders replaces the provider SDK with the
// worker source's copy, lists the sources' providers in the registry and
// refuses a module requiring a later SDK.
func TestBuildsCompileTheSourcesProviders(t *testing.T) {
	src := repoSource(t)
	p, err := planBuild(src, parse(t, withStamp(t, "")), set162(t), []string{stampModule})
	if err != nil {
		t.Fatal(err)
	}
	f, err := modfile.Parse("go.mod", p.goMod, nil)
	if err != nil {
		t.Fatal(err)
	}
	if requireOf(t, p.goMod, manifest.ProviderSDK) != "v"+provider.Version || !slices.ContainsFunc(f.Replace, func(r *modfile.Replace) bool {
		return r.Old.Path == manifest.ProviderSDK && r.New.Path == "./collector/provider"
	}) {
		t.Fatalf("go.mod does not replace the SDK:\n%s", p.goMod)
	}
	sources := []ModuleSource{{Module: stampModule, Origin: "testdata", Files: os.DirFS("../../../testdata/runtimes/stampprocessor")}}
	archive, err := p.writeArchive(src, p.goMod, p.goSum, sources)
	if err != nil {
		t.Fatal(err)
	}
	files := untar(t, archive)
	if !strings.Contains(files[providersFile], `"`+stampModule+`/stampdebug"`) || files["custom/0/stampdebug/provider.go"] == "" {
		t.Fatalf("providers.go:\n%s", files[providersFile])
	}
	if found, err := sourceProviders(sources); err != nil || len(found) != 1 || found[0].Name != "stamp" {
		t.Fatalf("providers %+v, %v", found, err)
	}

	later := fstest.MapFS{"go.mod": {Data: []byte("module " + stampModule + "\n\nrequire " + manifest.ProviderSDK + " v0.99.0\n")}}
	err = p.checkSources([]ModuleSource{{Module: stampModule, Files: later}})
	if err == nil || !strings.Contains(err.Error(), "requires the provider SDK v0.99.0; this debugger embeds v"+provider.Version) {
		t.Fatalf("got %v", err)
	}
}
