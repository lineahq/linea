func builtInManifest(t *testing.T) []byte {
	t.Helper()
	raw, err := os.ReadFile("../../../build/linea-runtime.yaml")
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

func parse(t *testing.T, raw []byte) *manifest.Manifest {
	t.Helper()
	m, err := manifest.Parse(raw)
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func repoSource(t *testing.T) fstest.MapFS {
	t.Helper()
	src := fstest.MapFS{}
	for _, name := range []string{"go.mod", "go.sum"} {
		data, err := os.ReadFile("../../../" + name)
		if err != nil {
			t.Fatal(err)
		}
		src[name] = &fstest.MapFile{Data: data}
	}
	src["internal/debugger/registry/components.go"] = &fstest.MapFile{Data: []byte("package registry // built-in\n")}
	src["internal/debugger/registry/registry.go"] = &fstest.MapFile{Data: []byte("package registry\n")}
	src[variantFile] = &fstest.MapFile{Data: []byte("package ottlcompat // built-in\n")}
	src[featureSetFile] = &fstest.MapFile{Data: []byte("package featureset // built-in\n")}
	src[providersFile] = &fstest.MapFile{Data: []byte("package registry // built-in\n")}
	src[releaseFile] = &fstest.MapFile{Data: []byte("package release // built-in\n")}
	return src
}

func untar(t *testing.T, archive []byte) map[string]string {
	t.Helper()
	zr, err := gzip.NewReader(bytes.NewReader(archive))
	if err != nil {
		t.Fatal(err)
	}
	tr := tar.NewReader(zr)
	out := map[string]string{}
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return out
		}
		if err != nil {
			t.Fatal(err)
		}
		data, err := io.ReadAll(tr)
		if err != nil {
			t.Fatal(err)
		}
		out[hdr.Name] = string(data)
	}
}

func set162(t *testing.T) *DependencySet {
	t.Helper()
	r := versions.Embedded().Release("0.162.0")
	if r == nil {
		t.Fatal("the support table has no 0.162.0")
	}
	return &DependencySet{GoMod: r.GoMod, GoSum: r.GoSum}
}

func requireOf(t *testing.T, goMod []byte, mod string) string {
	t.Helper()
	f, err := modfile.ParseLax("go.mod", goMod, nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range f.Require {
		if r.Mod.Path == mod {
			return r.Mod.Version
		}
	}
	return ""
}

// TestBuildPlanUsesTheDependencySet plans the built-in manifest: the
// registry is generated from the manifest, go.mod and go.sum are the
// release's dependency set, every other file is copied unchanged, and
// nothing needs resolving.
func TestBuildPlanUsesTheDependencySet(t *testing.T) {
	src := repoSource(t)
	set := set162(t)
	p, err := planBuild(src, parse(t, builtInManifest(t)), set, nil)
	if err != nil {
		t.Fatal(err)
	}
	if p.resolve || !p.verified || p.collectorVersion != "0.162.0" {
		t.Fatalf("resolve %v, verified %v, collector %q", p.resolve, p.verified, p.collectorVersion)
	}
	archive, err := p.writeArchive(src, p.goMod, p.goSum, nil)
	if err != nil {
		t.Fatal(err)
	}
	files := untar(t, archive)
	if len(files) != len(src) {
		t.Fatalf("build module has %d files, the source %d", len(files), len(src))
	}
	reg := files[registryFile]
	if !strings.Contains(reg, "Code generated by internal/debugger/registry/gen from the runtime's manifest") ||
		!strings.Contains(reg, "fileStorage()") {
		t.Fatalf("registry not generated from the manifest:\n%.600s", reg)
	}
	if rel := files[releaseFile]; !strings.Contains(rel, `const CollectorVersion = "0.162.0"`) ||
		!strings.Contains(rel, `"go.opentelemetry.io/collector/receiver/otlpreceiver v0.162.0"`) {
		t.Fatalf("release not generated from the manifest:\n%.600s", rel)
	}
	if files["go.sum"] != string(set.GoSum) || requireOf(t, []byte(files["go.mod"]), "go.opentelemetry.io/collector/otelcol") != "v0.162.0" {
		t.Fatal("the build module does not use the dependency set")
	}
	if !strings.Contains(files[variantFile], `/internal/debugger/compat/ottl/since0162"`) || !strings.Contains(files[featureSetFile], "internal/debugger/ottlreplay") {
		t.Fatalf("variant and features not generated from the manifest:\n%s\n%s", files[variantFile], files[featureSetFile])
	}
	if files["internal/debugger/registry/registry.go"] != string(src["internal/debugger/registry/registry.go"].Data) {
		t.Fatal("registry.go changed in the build module")
	}
	if !strings.HasPrefix(moduleSet(p.goSum), "sha256:") {
		t.Fatalf("module set %q", moduleSet(p.goSum))
	}
}

// TestBuildPlanRefusesModulesOffTheRelease names every core or contrib
// module at another version than the dependency set's, and a manifest for
// another release; a third-party module is added for resolution instead.
func TestBuildPlanRefusesModulesOffTheRelease(t *testing.T) {
	raw := string(builtInManifest(t))
	raw = strings.Replace(raw, "otelcol_version: 0.162.0", "otelcol_version: 0.161.0", 1)
	raw = strings.Replace(raw, "receiver/otlpreceiver v0.162.0", "receiver/otlpreceiver v0.161.0", 1)
	raw = strings.Replace(raw, "receivers:\n", "receivers:\n  - gomod: example.com/custom/receiver v1.2.3\n", 1)
	_, err := planBuild(repoSource(t), parse(t, []byte(raw)), set162(t), nil)
	var me *ModuleError
	if !errors.As(err, &me) {
		t.Fatalf("got %v, want a ModuleError", err)
	}
	want := []string{
		"dist.otelcol_version is 0.161.0, the dependency set is 0.162.0",
		"receivers[2]: go.opentelemetry.io/collector/receiver/otlpreceiver v0.161.0, the dependency set has v0.162.0",
	}
	for _, w := range want {
		if !strings.Contains(err.Error(), w) {
			t.Errorf("error does not say %q:\n%v", w, err)
		}
	}
	if len(me.Problems) != len(want) {
		t.Errorf("%d problems, want %d: %q", len(me.Problems), len(want), me.Problems)
	}
}

const stampModule = "example.com/linea/stampprocessor"

