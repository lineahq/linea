// TestBuildPlanAddsCustomModuleSources requires a sourced module at its
// manifest version, replaced by its directory in the build module, and
// writes the source there.
func TestBuildPlanAddsCustomModuleSources(t *testing.T) {
	src := repoSource(t)
	p, err := planBuild(src, parse(t, withStamp(t, "")), set162(t), []string{stampModule})
	if err != nil {
		t.Fatal(err)
	}
	if !p.resolve {
		t.Fatal("a custom module must be resolved")
	}
	f, err := modfile.Parse("go.mod", p.goMod, nil)
	if err != nil {
		t.Fatal(err)
	}
	if requireOf(t, p.goMod, stampModule) != "v0.1.0" || !slices.ContainsFunc(f.Replace, func(r *modfile.Replace) bool {
		return r.Old.Path == stampModule && r.New.Path == "./custom/0"
	}) {
		t.Fatalf("go.mod does not replace %s with its source:\n%s", stampModule, p.goMod)
	}
	sources := []ModuleSource{{Module: stampModule, Origin: "testdata", Files: os.DirFS("../../../testdata/runtimes/stampprocessor")}}
	archive, err := p.writeArchive(src, p.goMod, p.goSum, sources)
	if err != nil {
		t.Fatal(err)
	}
	files := untar(t, archive)
	if !strings.HasPrefix(files["custom/0/go.mod"], "module "+stampModule) || files["custom/0/factory.go"] == "" {
		t.Fatalf("the source is not in custom/0: %v", slices.Sorted(maps.Keys(files)))
	}
}

