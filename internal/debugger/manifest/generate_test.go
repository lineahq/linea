func TestOTTLVariantIsTheNewestAtOrBeforeTheRelease(t *testing.T) {
	const base = "github.com/lineahq/linea/internal/debugger/compat/ottl/"
	for version, want := range map[string]string{
		"0.160.0": "since0160",
		"0.160.1": "since0160",
		"0.161.0": "since0161",
		"0.162.0": "since0162",
		// A release newer than the support table builds with the newest
		// variants.
		"0.163.0": "since0162",
		"1.5.0":   "since0162",
	} {
		got, err := OTTLVariant(version)
		if err != nil || got != base+want {
			t.Errorf("OTTLVariant(%s) = %q, %v; want %s", version, got, err, want)
		}
	}
	for _, version := range []string{"0.159.0", "junk"} {
		if got, err := OTTLVariant(version); err == nil {
			t.Errorf("OTTLVariant(%s) = %q, want an error", version, got)
		}
	}
}

func TestEveryOTTLVariantHasItsPackage(t *testing.T) {
	entries, err := os.ReadDir(filepath.Join("..", "compat", "ottl"))
	if err != nil {
		t.Fatal(err)
	}
	var dirs []string
	for _, e := range entries {
		if e.IsDir() && strings.HasPrefix(e.Name(), "since") {
			dirs = append(dirs, e.Name())
		}
	}
	var want []string
	for _, v := range OTTLVariants {
		pkg, err := OTTLVariant(v)
		if err != nil {
			t.Fatal(err)
		}
		want = append(want, path.Base(pkg))
		src, err := os.ReadFile(filepath.Join("..", "compat", "ottl", path.Base(pkg), "ottl.go"))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(src), `const Since = "`+v+`"`) {
			t.Errorf("%s does not declare Since %s", path.Base(pkg), v)
		}
	}
	if !slices.Equal(dirs, want) {
		t.Fatalf("variant directories %v, OTTLVariants %v", dirs, want)
	}
}

