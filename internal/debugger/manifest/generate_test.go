func TestGenerateRegistryImportsEachComponentOnce(t *testing.T) {
	m, err := Parse([]byte(`
dist:
  otelcol_version: 0.162.0
receivers:
  - gomod: go.opentelemetry.io/collector/receiver/otlpreceiver v0.162.0
processors:
  - gomod: github.com/acme/a/batchprocessor v1.0.0
  - gomod: go.opentelemetry.io/collector/processor/batchprocessor v0.162.0
  - gomod: github.com/acme/receiver v1.0.0
exporters:
  - gomod: github.com/acme/storage v1.0.0
extensions:
  - gomod: github.com/acme/storage v1.0.0
`))
	if err != nil {
		t.Fatal(err)
	}
	src, err := GenerateRegistry(m, RegistryOptions{
		Package:   "registry",
		Source:    "test.yaml",
		Overrides: map[string]string{"github.com/acme/storage": "storage()"},
	})
	if err != nil {
		t.Fatal(err)
	}
	got := string(src)
	for _, want := range []string{
		"// Code generated by internal/debugger/registry/gen from test.yaml. DO NOT EDIT.",
		`"github.com/acme/a/batchprocessor"`,
		`batchprocessor2 "go.opentelemetry.io/collector/processor/batchprocessor"`,
		`receiver2 "github.com/acme/receiver"`,
		"batchprocessor2.NewFactory(),",
		"receiver2.NewFactory(),",
		"storage(),",
		`"go.opentelemetry.io/collector/service/telemetry/otelconftelemetry"`,
		"Telemetry: otelconftelemetry.NewFactory()",
		`{"github.com/acme/storage", typeNames("extensions", storage())},`,
		// The module of each factory, as OCB records it.
		"factories.ExtensionModules = modulesOf(factories.Extensions, map[component.Type]string{",
		`storage().Type(): "github.com/acme/storage v1.0.0",`,
		`batchprocessor2.NewFactory().Type(): "go.opentelemetry.io/collector/processor/batchprocessor v0.162.0",`,
		`{"go.opentelemetry.io/collector/processor/batchprocessor", typeNames("processors", batchprocessor2.NewFactory())},`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("generated registry lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, "\t\"github.com/acme/storage\"\n") {
		t.Errorf("overridden module imported:\n%s", got)
	}
}

