func TestGenerateFeatureSetImportsOnlyTheManifestsFeatures(t *testing.T) {
	packages := map[string]string{
		"github.com/open-telemetry/opentelemetry-collector-contrib/processor/transformprocessor": "example.com/ottlreplay",
		"github.com/open-telemetry/opentelemetry-collector-contrib/connector/countconnector":     "example.com/aggregation",
	}
	with, err := Parse([]byte(`
dist: {otelcol_version: 0.162.0}
processors:
  - gomod: github.com/open-telemetry/opentelemetry-collector-contrib/processor/transformprocessor v0.162.0
`))
	if err != nil {
		t.Fatal(err)
	}
	src, err := GenerateFeatureSet(with, packages, "a test")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), `_ "example.com/ottlreplay"`) || strings.Contains(string(src), "aggregation") {
		t.Fatalf("feature set:\n%s", src)
	}
	without, err := Parse([]byte(`
dist: {otelcol_version: 0.162.0}
processors:
  - gomod: go.opentelemetry.io/collector/processor/batchprocessor v0.162.0
`))
	if err != nil {
		t.Fatal(err)
	}
	src, err = GenerateFeatureSet(without, packages, "a test")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(src), "import (") || !strings.Contains(string(src), "package featureset") {
		t.Fatalf("feature set without features:\n%s", src)
	}
}

