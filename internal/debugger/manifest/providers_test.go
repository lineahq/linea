package manifest

import (
	"reflect"
	"testing"
	"testing/fstest"
)

func TestDiscoverProvidersFindsDebuggerProviders(t *testing.T) {
	file := func(src string) *fstest.MapFile { return &fstest.MapFile{Data: []byte(src)} }
	files := fstest.MapFS{
		"go.mod": file("module example.com/comp\n\ngo 1.25\n\nrequire github.com/lineahq/linea/collector/provider v0.1.0\n"),
		"debug/debug.go": file(`package debug

import "github.com/lineahq/linea/collector/provider"

const name = "comp"

func DebuggerProvider() provider.Provider {
	return provider.Provider{Name: name, Components: []provider.Type{{Kind: "extension", Type: "comp"}}}
}
`),
		"literal/p.go": file(`package literal

import sdk "github.com/lineahq/linea/collector/provider"

func DebuggerProvider() sdk.Provider { return sdk.Provider{Name: "lit"} }
`),
		"computed/p.go": file(`package computed

import "github.com/lineahq/linea/collector/provider"

func DebuggerProvider() provider.Provider { return provider.Provider{Name: names()} }

func names() string { return "x" }
`),
		// Another package's Provider type, internal packages and test files
		// are no providers.
		"other/p.go": file(`package other

import "example.com/elsewhere/provider"

func DebuggerProvider() provider.Provider { return provider.Provider{} }
`),
		"internal/hidden/p.go": file(`package hidden

import "github.com/lineahq/linea/collector/provider"

func DebuggerProvider() provider.Provider { return provider.Provider{Name: "hidden"} }
`),
		"debug/debug_test.go": file("package debug\n"),
	}
	module, got, sdk, err := DiscoverProviders(files)
	if err != nil {
		t.Fatal(err)
	}
	want := []Provider{
		{Import: "example.com/comp/computed"},
		{Import: "example.com/comp/debug", Name: "comp"},
		{Import: "example.com/comp/literal", Name: "lit"},
	}
	if module != "example.com/comp" || sdk != "v0.1.0" || !reflect.DeepEqual(got, want) {
		t.Fatalf("module %q, sdk %q, providers %+v", module, sdk, got)
	}
}

func TestGenerateProvidersListsEachPackage(t *testing.T) {
	src, err := GenerateProviders([]ProviderImport{{Package: "example.com/b"}, {Package: "example.com/a"}, {Package: "example.com/b"}}, "test")
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by internal/debugger/registry/gen from test. DO NOT EDIT.

package registry

import (
	provider0 "example.com/a"
	provider1 "example.com/b"
)

// Providers are the debugger providers of the component modules compiled
// into this registry, in import path order.
func Providers() []Provider {
	return []Provider{
		{Package: "example.com/a", New: provider0.DebuggerProvider},
		{Package: "example.com/b", New: provider1.DebuggerProvider},
	}
}
`
	if string(src) != want {
		t.Fatalf("generated:\n%s", src)
	}
}
